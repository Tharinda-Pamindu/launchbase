def _utcnow() -> datetime:
    return datetime.now(UTC)


def _in(column: str, values: tuple[str, ...]) -> str:
    """SQL for a CHECK that keeps a string column to a fixed set of values.

    String columns plus a CHECK stand in for enums, which don't play well with
    autogenerated migrations.
    """
    quoted = ", ".join(f"'{v}'" for v in values)
    return f"{column} IN ({quoted})"


class OrgRole:
    """A customer's role inside one organization.

    Not to be confused with platform staff, which is `User.is_admin` and only
    ever grants access to the internal surface. An org `ADMIN` is a customer.
    """

    OWNER = "owner"
    ADMIN = "admin"
    MEMBER = "member"
    ALL = (OWNER, ADMIN, MEMBER)
    # Roles that manage members, teams and settings.
    MANAGERS = (OWNER, ADMIN)
    # Roles an invite can grant; ownership is only ever given by an owner.
    INVITABLE = (ADMIN, MEMBER)


