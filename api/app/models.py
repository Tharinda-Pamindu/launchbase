class Team(IdMixin, TimestampMixin, Base):
    __tablename__ = "teams"
    __table_args__ = (
        UniqueConstraint("organization_id", "name"),
        # Target of the composite foreign key on team_memberships.
        UniqueConstraint("organization_id", "id"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False
    )
    name: Mapped[str] = mapped_column(String(100), nullable=False)
    description: Mapped[str | None] = mapped_column(String(500), nullable=True)

    memberships: Mapped[list[TeamMembership]] = relationship(
        back_populates="team", passive_deletes=True
    )


class TeamMembership(IdMixin, TimestampMixin, Base):
    __tablename__ = "team_memberships"
    __table_args__ = (
        UniqueConstraint("team_id", "user_id"),
        # Composite keys tie both sides to the same organization, so a team can
        # never hold someone from another org, and leaving the org (or deleting
        # the team) removes the row.
        ForeignKeyConstraint(
            ["organization_id", "team_id"],
            ["teams.organization_id", "teams.id"],
            ondelete="CASCADE",
        ),
        ForeignKeyConstraint(
            ["organization_id", "user_id"],
            [
                "organization_memberships.organization_id",
                "organization_memberships.user_id",
            ],
            ondelete="CASCADE",
        ),
        # At most one lead per team.
        Index(
            "uq_team_memberships_one_lead",
            "team_id",
            unique=True,
            postgresql_where=text("is_lead"),
        ),
        Index("ix_team_memberships_org_user", "organization_id", "user_id"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(nullable=False)
    team_id: Mapped[uuid.UUID] = mapped_column(nullable=False)
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    is_lead: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)

    team: Mapped[Team] = relationship(back_populates="memberships")
    user: Mapped[User] = relationship()


class WeeklyPlan(IdMixin, TimestampMixin, Base):
    __tablename__ = "weekly_plans"
    __table_args__ = (
        UniqueConstraint("organization_id", "user_id", "week_start"),
        Index("ix_weekly_plans_org_week", "organization_id", "week_start"),
        CheckConstraint(_in("status", PlanStatus.ALL), name="ck_weekly_plan_status"),
        CheckConstraint(
            "EXTRACT(ISODOW FROM week_start) = 1", name="ck_weekly_plan_monday"
        ),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False
    )
    # Plans belong to the person, not a team, and outlive team changes so the
    # history stays intact.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    week_start: Mapped[date] = mapped_column(Date, nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False)
    submitted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    approved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    approved_by_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    main_goal_shipped: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    outcome_note: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    # Latest AI review, already mapped to task ids. `ai_review_plan_hash` is the
    # plan content it was made for, so the UI can mark it stale after edits.
    ai_review: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    ai_reviewed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    ai_review_plan_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)

    user: Mapped[User] = relationship(foreign_keys=[user_id])
    tasks: Mapped[list[PlanTask]] = relationship(
        back_populates="plan",
        order_by="PlanTask.position",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    reviews: Mapped[list[PlanReview]] = relationship(
        back_populates="plan",
        order_by="PlanReview.created_at",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class PlanTask(IdMixin, TimestampMixin, Base):
    __tablename__ = "plan_tasks"
    __table_args__ = (
        CheckConstraint(_in("kind", TaskKind.ALL), name="ck_plan_task_kind"),
        CheckConstraint(
            "estimate_hours IS NULL OR estimate_hours BETWEEN 1 AND 60",
            name="ck_plan_task_estimate_hours",
        ),
        # Exactly one main task is enforced at submit; the DB guarantees there is
        # never more than one.
        Index(
            "uq_plan_tasks_one_main",
            "plan_id",
            unique=True,
            postgresql_where=text("kind = 'main'"),
        ),
    )

    plan_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("weekly_plans.id", ondelete="CASCADE"), nullable=False, index=True
    )
    kind: Mapped[str] = mapped_column(String(20), nullable=False)
    title: Mapped[str] = mapped_column(String(300), nullable=False)
    # Why the main task matters; only the main task has one.
    why: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    estimate_hours: Mapped[int | None] = mapped_column(Integer, nullable=True)
    position: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    is_done: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    done_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    plan: Mapped[WeeklyPlan] = relationship(back_populates="tasks")


class PlanReview(IdMixin, TimestampMixin, Base):
    """A lead's decision on a submitted plan: approve or send back."""

    __tablename__ = "plan_reviews"
    __table_args__ = (
        CheckConstraint(_in("action", ReviewAction.ALL), name="ck_plan_review_action"),
    )

    plan_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("weekly_plans.id", ondelete="CASCADE"), nullable=False, index=True
    )
    reviewer_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    action: Mapped[str] = mapped_column(String(30), nullable=False)
    comment: Mapped[str | None] = mapped_column(String(2000), nullable=True)

    plan: Mapped[WeeklyPlan] = relationship(back_populates="reviews")
    reviewer: Mapped[User | None] = relationship()


class AiUsageEvent(IdMixin, TimestampMixin, Base):
    """One call to the AI feature, successful or not. Metadata only: no prompt
    or output text is stored here."""

    __tablename__ = "ai_usage_events"
    __table_args__ = (
        CheckConstraint(_in("operation", AiOperation.ALL), name="ck_ai_usage_op"),
        CheckConstraint(_in("outcome", AiOutcome.ALL), name="ck_ai_usage_outcome"),
        Index("ix_ai_usage_events_org_created", "organization_id", "created_at"),
        Index("ix_ai_usage_events_user_created", "user_id", "created_at"),
        Index("ix_ai_usage_events_created", "created_at"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    operation: Mapped[str] = mapped_column(String(30), nullable=False)
    outcome: Mapped[str] = mapped_column(String(20), nullable=False)
    # Short machine-readable reason for a failure, e.g. "timeout".
    error_kind: Mapped[str | None] = mapped_column(String(50), nullable=True)
    model: Mapped[str] = mapped_column(String(100), nullable=False)
    latency_ms: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    input_tokens: Mapped[int | None] = mapped_column(Integer, nullable=True)
    output_tokens: Mapped[int | None] = mapped_column(Integer, nullable=True)
